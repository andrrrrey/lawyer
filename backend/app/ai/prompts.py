"""Шаблоны промптов AI-слоя (интерпретация показателей и рекомендации)."""

from __future__ import annotations

SYSTEM_PROMPT = (
    "Ты аналитик отдела маркетинга. По сводным данным сквозной аналитики находи "
    "закономерности, отклонения и риски, не видимые из обычных статистических "
    "показателей. Пиши кратко, по-русски, без выдуманных чисел — только на основе "
    "переданных данных. Не давай прямых указаний по изменению рекламных кабинетов."
)


def insights_prompt(summary: dict) -> str:
    """Промпт для генерации инсайтов по сводке аналитики."""
    return (
        "Сводка по каналам, кампаниям и воронке:\n"
        f"{summary}\n\n"
        "Сформируй до 5 инсайтов. Для каждого укажи: заголовок, что видно на "
        "дашборде, объяснение, рекомендацию, источники данных и достоверность."
    )


def budget_recs_prompt(summary: dict) -> str:
    """Промпт для рекомендаций по рекламному бюджету на основе сводки по каналам."""
    return (
        "Сводка по каналам, кампаниям и воронке (реальные показатели за период):\n"
        f"{summary}\n\n"
        "Сформируй до 5 рекомендаций по распределению рекламного бюджета — по каналам "
        "с ненулевым расходом. Опирайся на окупаемость по фактической выручке 1С "
        "(ROMI = (выручка − расход) / расход): "
        "прибыльные каналы масштабировать, убыточные — ограничивать. "
        "Для каждой рекомендации укажи: заголовок (канал или тема), действие "
        "(одно из: Масштабировать, Под наблюдением, Проверить, Ограничить), "
        "рекомендацию (что сделать), обоснование «как найдено» (со ссылкой на "
        "переданные числа: расход, выручку и ROMI), ожидаемый эффект, "
        "источники данных и достоверность (высокая|средняя|низкая)."
    )


def deal_comment_prompt(deal: dict) -> str:
    """Промпт для короткого комментария AI по сделке/лиду."""
    return (
        "Данные сделки:\n"
        f"{deal}\n\n"
        "Дай короткий комментарий (1 предложение) о риске или точке внимания."
    )
